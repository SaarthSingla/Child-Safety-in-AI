// Packs the real Cedar engine into one self-contained web page. The wallet
// runs it in a hidden WebView with no network access, so the same Cedar build
// works on iPhone and Android without any native code.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const wallet = dirname(dirname(fileURLToPath(import.meta.url)));
const web = join(wallet, '..', 'policy', 'node_modules', '@cedar-policy', 'cedar-wasm', 'web');

const glue = readFileSync(join(web, 'cedar_wasm.js'), 'utf8')
  .replace(/^export function /gm, 'function ')
  .replace(/^export \{ initSync \};$/m, '')
  .replace(/^export default __wbg_init;$/m, '')
  .replace("new URL('cedar_wasm_bg.wasm', import.meta.url)", "''");
if (/^export /m.test(glue) || glue.includes('import.meta')) throw new Error('The Cedar web build changed; update this script.');

const wasm = readFileSync(join(web, 'cedar_wasm_bg.wasm')).toString('base64');

const runner = `
var binary = atob(WASM);
var bytes = new Uint8Array(binary.length);
for (var i = 0; i < binary.length; i += 1) bytes[i] = binary.charCodeAt(i);
initSync({ module: bytes });

function send(message) {
  window.ReactNativeWebView.postMessage(JSON.stringify(message));
}

function one(policies, request) {
  var resource = { type: 'Content', id: 'item' };
  var child = { type: 'Child', id: 'child' };
  var answer = isAuthorized({
    principal: child,
    action: { type: 'Action', id: 'view' },
    resource: resource,
    context: request.context,
    validateRequest: false,
    policies: { staticPolicies: policies },
    entities: [
      { uid: resource, attrs: request.attributes, parents: [] },
      { uid: child, attrs: {}, parents: [] }
    ]
  });
  if (answer.type !== 'success') return { denied: false, reasons: [], errors: 1 };
  return {
    denied: answer.response.decision === 'deny',
    reasons: answer.response.diagnostics.reason,
    errors: answer.response.diagnostics.errors.length
  };
}

window.__authorize = function (id, json) {
  try {
    var input = JSON.parse(json);
    send({ id: id, results: input.requests.map(function (request) { return one(input.policies, request); }) });
  } catch (error) {
    send({ id: id, error: String(error) });
  }
};

send({ ready: true, version: getCedarVersion() });
`;

const html = `<!doctype html><html><head><meta charset="utf-8"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline' 'wasm-unsafe-eval'"></head><body><script>(function () {
var WASM = "${wasm}";
${glue}
${runner}
})();</script></body></html>`;

writeFileSync(join(wallet, 'src', 'nlpps', 'cedarEngineHtml.js'), `// Generated by scripts/build-cedar-engine.mjs. Do not edit.\nmodule.exports = ${JSON.stringify(html)};\n`);
writeFileSync(join(wallet, 'src', 'nlpps', 'cedarEngineHtml.d.ts'), 'declare const html: string;\nexport default html;\n');
console.log(`Cedar engine page: ${(html.length / 1024 / 1024).toFixed(1)} MB`);
